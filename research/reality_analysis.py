"""
Summarise a reality_eval.py run: accuracy on the original vs the realistic wording of the same 508
questions, a paired test (exact McNemar on the questions where only one version is right, plus a
question-level bootstrap of the difference), and abstention at the calibrated threshold on both.

    python research/reality_analysis.py --run-id RL-001

Writes results/reality/spider_realistic_<run>.md and .json. Only measured numbers.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import random
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
OUT = os.path.join(REPO, "results", "reality")


def mcnemar_exact(b: int, c: int) -> float:
    """Two-sided exact McNemar p-value for b and c discordant pairs (binomial, p = 0.5)."""
    n, k = b + c, min(b, c)
    if n == 0:
        return 1.0
    p = sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n
    return min(1.0, 2 * p)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-id", default="RL-001")
    args = ap.parse_args()
    from querygenie.pipeline import ABSTAIN_TAU

    rows = [json.loads(l) for l in open(os.path.join(OUT, f"spider_realistic_{args.run_id}.jsonl"))]
    by = {}
    for r in rows:
        by.setdefault(r["i"], {})[r["version"]] = r
    pairs = [(v["original"], v["realistic"]) for v in by.values() if "original" in v and "realistic" in v]
    n = len(pairs)

    def side(k):
        recs = [p[k] for p in pairs]
        correct = sum(r["correct"] for r in recs)
        ans = [r for r in recs if r["runs"] and r["confidence"] >= ABSTAIN_TAU]
        by_agree = {}
        for r in recs:
            a = round(r["agreement"] * 4) if r["runs"] else 0
            by_agree.setdefault(a, []).append(r["correct"])
        return {"ex": 100 * correct / n, "correct": correct,
                "coverage": 100 * len(ans) / n, "acc_answered": 100 * sum(r["correct"] for r in ans) / max(1, len(ans)),
                "wrong_answers": sum(1 for r in ans if not r["correct"]),
                "wrong_if_all": n - correct,
                "by_agreement": {a: {"n": len(v), "acc": 100 * sum(v) / len(v)} for a, v in sorted(by_agree.items())}}

    o, r = side(0), side(1)
    only_orig = sum(1 for a, b in pairs if a["correct"] and not b["correct"])
    only_real = sum(1 for a, b in pairs if b["correct"] and not a["correct"])
    rng = random.Random(42)
    diffs = []
    for _ in range(10000):
        s = [pairs[rng.randrange(n)] for _ in range(n)]
        diffs.append(100 * sum(a["correct"] - b["correct"] for a, b in s) / n)
    diffs.sort()
    res = {"run_id": args.run_id, "pairs": n, "tau": ABSTAIN_TAU, "original": o, "realistic": r,
           "gap_pts": o["ex"] - r["ex"], "only_original_right": only_orig, "only_realistic_right": only_real,
           "mcnemar_p": mcnemar_exact(only_orig, only_real),
           "bootstrap_ci_gap": [diffs[249], diffs[9749]]}
    json.dump(res, open(os.path.join(OUT, f"spider_realistic_{args.run_id}.json"), "w"), indent=2)

    f = lambda x: f"{x:.1f}%"
    md = [f"# Benchmark-to-reality gap: Spider-Realistic ({args.run_id})", "",
          "Generated by `research/reality_analysis.py` from `research/reality_eval.py`. The same "
          f"{n} Spider dev questions in their original wording and in the Spider-Realistic wording (column names "
          "removed; same databases and gold SQL), both through the evaluated CodeS-1B pipeline on the same machine, "
          "scored with the official Spider execution match.", "",
          "| | Original wording | Realistic wording |", "|---|---|---|",
          f"| Execution accuracy, answering everything | {f(o['ex'])} ({o['correct']}/{n}) | {f(r['ex'])} ({r['correct']}/{n}) |",
          f"| Balanced setting: questions answered | {f(o['coverage'])} | {f(r['coverage'])} |",
          f"| Balanced setting: accuracy on answered | {f(o['acc_answered'])} | {f(r['acc_answered'])} |",
          f"| Wrong answers given: answering everything → balanced | {o['wrong_if_all']} → {o['wrong_answers']} | {r['wrong_if_all']} → {r['wrong_answers']} |", "",
          f"- Gap: {res['gap_pts']:.1f} points (bootstrap 95% CI [{res['bootstrap_ci_gap'][0]:.1f}, {res['bootstrap_ci_gap'][1]:.1f}]).",
          f"- Right only in the original wording: {only_orig}; only in the realistic wording: {only_real}; "
          f"exact McNemar p = {res['mcnemar_p']:.2g}.", "",
          "Accuracy by number of agreeing candidates (realistic wording):", "",
          "| Agreeing | Questions | Accuracy |", "|---|---|---|"]
    md += [f"| {a} of 4 | {v['n']} | {f(v['acc'])} |" for a, v in r["by_agreement"].items()]
    open(os.path.join(OUT, f"spider_realistic_{args.run_id}.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
