"""
False-alarm check for the "all of what?" safeguard (querygenie/mentions.py): run it over every Spider
development question - each of which names what it asks about - and count how many it would wrongly
call unclear. Writes results/unclear_check.md.

    python research/app-checks/check_unclear.py
"""
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, REPO)
from querygenie.mentions import is_unclear, schema_mentions  # noqa: E402
from querygenie.pipeline import load_db_comments, matched_contents_for  # noqa: E402
from querygenie.vendor.codes_db_utils import get_db_schema  # noqa: E402

SPIDER = os.path.join(REPO, "data", "spider_full", "spider_data")
VAGUE = ["show me all", "how many are there?", "show everything", "give me the data", "what is the total?",
         "list everything in the database"]


def main():
    dev = json.load(open(os.path.join(SPIDER, "dev.json")))
    comments = load_db_comments(os.path.join(SPIDER, "tables.json"))
    schemas, flagged = {}, []
    for q in dev:
        db = q["db_id"]
        path = os.path.join(SPIDER, "database", db, db + ".sqlite")
        schemas.setdefault(db, get_db_schema(path, comments, db))
        m = schema_mentions(schemas[db], q["question"])
        if is_unclear(m):
            m = schema_mentions(schemas[db], q["question"], matched_contents_for(path, schemas[db], q["question"]))
        if is_unclear(m):
            flagged.append((db, q["question"]))
    caught = {}
    for v in VAGUE:                              # the same vague requests on every development database
        n = sum(is_unclear(schema_mentions(s, v)) for s in schemas.values())
        caught[v] = n
    lines = ["# 'All of what?' safeguard — false-alarm check", "",
             "Generated by `research/app-checks/check_unclear.py` (no model needed).", "",
             f"- Spider development questions wrongly called unclear: **{len(flagged)} of {len(dev)}**",
             *[f"  - {db}: {q}" for db, q in flagged], "",
             f"Vague requests called unclear, on each of the {len(schemas)} development databases:", "",
             "| Request | Databases where it is called unclear |", "|---|---|",
             *[f"| {v} | {n} / {len(schemas)} |" for v, n in caught.items()]]
    open(os.path.join(REPO, "results", "unclear_check.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
