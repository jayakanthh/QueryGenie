"""
Agreement for choosing an answer, not only for abstaining?

From the saved four-candidate record of run T2-006 (no model needed), compares the CodeS selection rule
(first candidate that executes) with a majority vote over the candidates' results, and the upper bound
of picking whichever candidate is correct. Writes results/selection_analysis.{json,md}.

    python research/selection_analysis.py
"""
import collections
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def majority(r):
    ok = [i for i in range(4) if r["exec_ok"][i] and r["result_hash"][i] is not None]
    if not ok:
        return r["selected"]
    count = collections.Counter(r["result_hash"][i] for i in ok)
    best = max(count.values())
    return next(i for i in ok if count[r["result_hash"][i]] == best)     # ties: the earliest beam


def main():
    rows = [json.loads(l) for l in open(os.path.join(REPO, "results", "dump_T2-006.jsonl"))]
    n = len(rows)
    first = sum(r["selected_official_correct"] for r in rows)
    vote = sum(r["official_correct"][majority(r)] for r in rows)
    oracle = sum(any(r["official_correct"]) for r in rows)
    changed = [r for r in rows if majority(r) != r["selected"]]
    res = {"questions": n,
           "first_executable": {"correct": first, "ex": round(100 * first / n, 2)},
           "majority_vote": {"correct": vote, "ex": round(100 * vote / n, 2), "selection_changed": len(changed),
                             "changed_now_correct": sum(r["official_correct"][majority(r)] > r["selected_official_correct"] for r in changed),
                             "changed_now_wrong": sum(r["official_correct"][majority(r)] < r["selected_official_correct"] for r in changed)},
           "oracle": {"correct": oracle, "ex": round(100 * oracle / n, 2)}}
    json.dump(res, open(os.path.join(REPO, "results", "selection_analysis.json"), "w"), indent=2)
    mv = res["majority_vote"]
    md = ["# Choosing among the four candidates (run T2-006)", "",
          "Generated by `research/selection_analysis.py` from `results/dump_T2-006.jsonl` (no model run).", "",
          "| Selection rule | Correct | EX |", "|---|---|---|",
          f"| First candidate that executes (CodeS, reproduced) | {first} | {res['first_executable']['ex']}% |",
          f"| Majority vote over the candidates' results (ties: earliest beam) | {vote} | {mv['ex']}% |",
          f"| Upper bound: a correct candidate is among the four | {oracle} | {res['oracle']['ex']}% |", "",
          f"Majority vote changes the selection on {mv['selection_changed']} questions: "
          f"{mv['changed_now_correct']} become correct, {mv['changed_now_wrong']} become wrong."]
    open(os.path.join(REPO, "results", "selection_analysis.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
