"""
Data collection and preliminary analysis for the report (Chapter 3).

Computes, from the Spider files and the committed T2-006 candidate record (no model needed):
  - split sizes and databases per split
  - schema size of the development databases (tables, columns, foreign keys)
  - SQL features of the development-set gold queries
  - the official Spider difficulty level of every development question, and the reproduced
    CodeS-1B Execution Accuracy per level (selected_official_correct in results/dump_T2-006.jsonl)

The difficulty levels come from the official evaluator's own classifier (Evaluator.eval_hardness in
https://github.com/taoyds/test-suite-sql-eval, the evaluator used by research/colab_eval_tier2.py).

    python research/dataset_analysis.py --evaluator /path/to/test-suite-sql-eval
    -> results/dataset_analysis.json, results/dataset_analysis.md
"""
import argparse
import collections
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPIDER = os.path.join(REPO, "data", "spider_full", "spider_data")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--evaluator", required=True, help="checkout of taoyds/test-suite-sql-eval")
    ap.add_argument("--dump", default=os.path.join(REPO, "results", "dump_T2-006.jsonl"))
    args = ap.parse_args()
    sys.path.insert(0, args.evaluator)
    from evaluation import Evaluator                      # official difficulty classifier
    from process_sql import Schema, get_schema, get_sql

    load = lambda f: json.load(open(os.path.join(SPIDER, f)))
    train, others, dev = load("train_spider.json"), load("train_others.json"), load("dev.json")
    tables = {t["db_id"]: t for t in load("tables.json")}
    out = {"splits": {
        "train_spider": {"questions": len(train), "databases": len({q["db_id"] for q in train})},
        "train_others": {"questions": len(others), "databases": len({q["db_id"] for q in others})},
        "dev": {"questions": len(dev), "databases": len({q["db_id"] for q in dev})}}}
    tr_db = {q["db_id"] for q in train + others}
    out["dev_databases_seen_in_training"] = len({q["db_id"] for q in dev} & tr_db)

    # schema size of the 20 development databases
    dev_dbs = sorted({q["db_id"] for q in dev})
    sizes = [(len(tables[d]["table_names_original"]), len(tables[d]["column_names_original"]) - 1,
              len(tables[d]["foreign_keys"])) for d in dev_dbs]
    stat = lambda xs: {"min": min(xs), "max": max(xs), "mean": round(sum(xs) / len(xs), 2), "total": sum(xs)}
    out["dev_schema"] = {"tables": stat([s[0] for s in sizes]), "columns": stat([s[1] for s in sizes]),
                         "foreign_keys": stat([s[2] for s in sizes])}
    qpd = collections.Counter(q["db_id"] for q in dev)
    out["dev_questions_per_database"] = stat(list(qpd.values()))

    # SQL features of the gold queries (keyword presence, case-insensitive)
    feats = {"JOIN": r"\bjoin\b", "GROUP BY": r"\bgroup\s+by\b", "ORDER BY": r"\border\s+by\b",
             "HAVING": r"\bhaving\b", "nested SELECT": r"\(\s*select\b",
             "set operation (UNION/INTERSECT/EXCEPT)": r"\b(union|intersect|except)\b", "LIMIT": r"\blimit\b"}
    out["dev_gold_sql_features"] = {k: sum(bool(re.search(p, q["query"], re.I)) for q in dev) for k, p in feats.items()}

    # official difficulty per question, and reproduced accuracy per level
    ev = Evaluator()
    dump = [json.loads(l) for l in open(args.dump)]
    assert len(dump) == len(dev) and all(d["question"] == q["question"] for d, q in zip(dump, dev))
    per = collections.defaultdict(lambda: [0, 0])
    for q, d in zip(dev, dump):
        schema = Schema(get_schema(os.path.join(SPIDER, "database", q["db_id"], q["db_id"] + ".sqlite")))
        level = ev.eval_hardness(get_sql(schema, q["query"]))
        per[level][0] += 1
        per[level][1] += int(d["selected_official_correct"])        # the returned (selected) query
    order = ["easy", "medium", "hard", "extra"]
    out["dev_by_difficulty"] = {k: {"questions": per[k][0], "correct": per[k][1],
                                    "ex": round(100 * per[k][1] / per[k][0], 1)} for k in order}
    total_correct = sum(v[1] for v in per.values())
    out["dev_total_correct"] = total_correct
    assert total_correct == sum(int(d["selected_official_correct"]) for d in dump) == 804, total_correct  # T2-006

    json.dump(out, open(os.path.join(REPO, "results", "dataset_analysis.json"), "w"), indent=2)
    md = ["# Dataset analysis (Spider)", "", "Generated by `research/dataset_analysis.py`.", "",
          "| Split | Questions | Databases |", "|---|---|---|"]
    md += [f"| {k} | {v['questions']:,} | {v['databases']} |" for k, v in out["splits"].items()]
    md += ["", f"Development databases also used in training: {out['dev_databases_seen_in_training']}.", "",
           "| Difficulty | Questions | Correct (T2-006) | EX |", "|---|---|---|---|"]
    md += [f"| {k} | {v['questions']} | {v['correct']} | {v['ex']}% |" for k, v in out["dev_by_difficulty"].items()]
    md += [f"| all | {len(dev)} | {total_correct} | {100 * total_correct / len(dev):.1f}% |"]
    open(os.path.join(REPO, "results", "dataset_analysis.md"), "w").write("\n".join(md) + "\n")
    print(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
